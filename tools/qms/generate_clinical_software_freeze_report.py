#!/usr/bin/env python3
from qms_lib import ROOT, evidence_artifact_rel, evidence_artifact_path

OUT = ROOT / "qms" / "generated" / "ClinicalSoftwareFreezeReport.md"


def exists_rel(key: str) -> str:
    path = evidence_artifact_path(key)
    return "present" if path and path.exists() else "missing"


def main() -> None:
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(f"""# ClinicalSoftwareFreezeReport

## Software build status
- Normal build lane: `cmake -S . -B build && cmake --build build -j2`.
- Active normal CTest lane: `ctest --test-dir build --output-on-failure`.
- Bounded readiness transcript: {exists_rel('readiness_lane_transcript_bounded')} (`{evidence_artifact_rel('readiness_lane_transcript_bounded')}`).
- Full 10k readiness transcript: {exists_rel('readiness_lane_transcript_full10k')} (`{evidence_artifact_rel('readiness_lane_transcript_full10k')}`).

## Evidence inventory
- Evidence index: {'present' if (ROOT / 'qms/generated/EvidenceIndex.json').exists() else 'missing'} (`qms/generated/EvidenceIndex.json`).
- HIL session evidence: {exists_rel('hil_session_report')} (`{evidence_artifact_rel('hil_session_report')}`).
- HIL latency evidence: {exists_rel('hil_latency_report')} (`{evidence_artifact_rel('hil_latency_report')}`).
- HIL risk coverage: {exists_rel('hil_risk_coverage')} (`{evidence_artifact_rel('hil_risk_coverage')}`).
- Runtime bounded evidence: {exists_rel('runtime_10k_bounded')} (`{evidence_artifact_rel('runtime_10k_bounded')}`).
- Runtime full 10k evidence: {exists_rel('runtime_10k_full')} (`{evidence_artifact_rel('runtime_10k_full')}`).
- Cybersecurity executed evidence package 0.4.4: {exists_rel('cybersecurity_vulnerability_scan')} (`{evidence_artifact_rel('cybersecurity_vulnerability_scan')}`).

## Open software/QMS gaps
- EvidenceRepository and ReviewGate are the promotion path for advanced readiness decisions.
- Evidence selection is manifest-driven; QMS generators must not infer current evidence from modification time.
- ClinicalTestAcceptanceReviewReady is the current software/QMS target for expert review preparation.
- ClinicalTestReady remains blocked unless required artifacts are signed by named independent reviewers and external clinical/regulatory records exist.
- Full 10k evidence is only valid when generated by `DNXR_CONTROLLER_10K_FULL=1 tools/qms/generate_runtime_10k_full_evidence.py`.

## Open non-software blockers
- Physical HIL bench execution on qualified hardware.
- Phantom qualification and target-hardware latency measurement.
- Independent safety, risk, cybersecurity, physician, and regulatory sign-off.
- Canada ITA / US IDE package review by qualified regulatory owners.
- REB/IRB approval and authorized clinical protocol execution.

## Freeze conclusion
The software/QMS package is suitable for clinical-test acceptance review preparation by qualified experts. Further clinical-test claims are externally evidence-blocked until physical HIL, named sign-off, cybersecurity execution review, and clinical/regulatory authorization records are available.
""", encoding="utf-8")
    print(OUT)


if __name__ == "__main__":
    main()
